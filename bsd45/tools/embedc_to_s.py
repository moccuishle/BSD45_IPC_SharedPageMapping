#!/usr/bin/env python3
"""embedc_to_s.py - turn build/embed.c back into a PE assembler source.

build/embed.c embeds the stage1/stage2/hello/init images into the kernel as
plain byte arrays.  When the compiler's child process (cc1) is unavailable but
GNU as is not, the arrays can be re-assembled from the generated C file:
every `const unsigned char x[] = {...}` becomes a .byte block and every
`const unsigned int x_len = N` becomes a .long.

Usage:
    python embedc_to_s.py <embed.c> <out.s>
then:
    as --32 -o embed.o embed.s
"""

import re
import sys


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    src, dst = argv[1], argv[2]
    text = open(src, "r", encoding="utf-8", errors="replace").read()

    arrays = []
    for m in re.finditer(r"const\s+unsigned\s+char\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\};",
                         text, re.S):
        name = m.group(1)
        body = m.group(2)
        vals = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{1,2})", body)]
        arrays.append((name, vals))

    lens = {}
    for m in re.finditer(r"const\s+unsigned\s+int\s+(\w+)\s*=\s*(\d+)\s*;", text):
        lens[m.group(1)] = int(m.group(2))

    if not arrays:
        print("no arrays found in %s" % src)
        return 1

    out = []
    out.append('/* generated by embedc_to_s.py from %s */' % src)
    out.append('.section .rdata,"dr"')
    for name, vals in arrays:
        sym = "_" + name
        out.append(".globl %s" % sym)
        out.append("%s:" % sym)
        for i in range(0, len(vals), 16):
            out.append("  .byte " + ",".join("0x%02x" % v for v in vals[i:i + 16]))
        out.append("  .balign 4")
        # length symbol, normally declared right after the array
        lname = name + "_len"
        if lname in lens:
            out.append(".globl _%s" % lname)
            out.append("_%s:" % lname)
            out.append("  .long %d" % lens[lname])
        print("  %-20s %6d bytes (len sym: %s)" %
              (name, len(vals), lens.get(lname, "missing")))

    open(dst, "w", encoding="ascii").write("\n".join(out) + "\n")
    print("wrote %s (%d arrays)" % (dst, len(arrays)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
